-- BK_BENCH.sql -- how fast the close of a day is with many accounts. On an empty bank (INSTALL.sql without
-- demo, no entries yet), as its owner:
--
--   sqlplus bank/<password>@FREEPDB1 @BK_BENCH.sql 1000000
--
-- It makes N accounts (a customer for every 2; the products CUR, BUS, SAV, SAVP in turn), each with a deposit
-- on the first day 30/12/2026, and one account in 10 a second one with a value date on the next day; then it
-- closes 30/12 (a day as any other) and 31/12 (the end of a month, of a quarter and of a year: all the
-- accounts capitalize), and says how long each took. The accounts made set-based (not through BK_CORE one by
-- one). Not for a bank with real data: UNINSTALL.sql and INSTALL.sql after it.
set serveroutput on
set verify off
set feedback off
whenever sqlerror exit failure rollback
column 1 new_value 1 noprint
select '' "1" from dual where rownum = 0;
define bench_n = "&1"

-- the numbers 1 .. N (a table of them: connect by runs out of memory for millions)
drop table if exists bk_bench_n purge;
create table bk_bench_n (r number constraint bk_bench_n_pk primary key) organization index;
insert /*+ append */ into bk_bench_n
select (a.r - 1) * 10000 + b.r from
  (select level r from dual connect by level <= ceil(to_number(nvl('&bench_n', '100000')) / 10000)) a,
  (select level r from dual connect by level <= 10000) b
where (a.r - 1) * 10000 + b.r <= to_number(nvl('&bench_n', '100000'));
commit;

declare
  cnt number := to_number(nvl('&bench_n', '100000'));
  d1 date := date '2026-12-30';
  c0 number;
  a0 number;
  e0 number;
  k number;
  t number;
  procedure say(p varchar2) is
  begin
    dbms_output.put_line(to_char(systimestamp, 'HH24:MI:SS') || '  ' || p);
  end;
  procedure identity_on(p_table varchar2) is
  begin
    execute immediate 'alter table ' || p_table || ' modify id generated by default on null as identity (start with limit value)';
  end;
begin
  select count(*) into k from bk_entry;
  if k > 0 then
    raise_application_error(-20001, 'BK_BENCH: an empty bank only (INSTALL.sql without demo)');
  end if;
  bk_core.set_start(d1);
  select nvl(max(id), 0) into c0 from bk_customer;
  select nvl(max(id), 0) into a0 from bk_account;
  select nvl(max(id), 0) into e0 from bk_entry;
  t := dbms_utility.get_time;
  insert /*+ append */ into bk_customer (id, code, name)
  select c0 + r, 'B' || (c0 + r), 'Bench ' || r from bk_bench_n where r <= ceil(cnt / 2);
  commit;
  insert /*+ append */ into bk_account (id, iban, product_id, opened_on, balance)
  select a0 + x.r, 'GR' || lpad(98 - mod(to_number(x.bban || '162700'), 97), 2, '0') || x.bban, p.id, d1, 0
  from (select r, '9990001' || lpad(a0 + r, 16, '0') bban, mod(r, 4) pk from bk_bench_n where r <= cnt) x
  join (select id, decode(code, 'CUR', 0, 'BUS', 1, 'SAV', 2, 3) pk from bk_product where code in ('CUR', 'BUS', 'SAV', 'SAVP')) p
    on p.pk = x.pk;
  commit;
  insert /*+ append */ into bk_holder (account_id, customer_id, role)
  select a0 + r, c0 + ceil(r / 2), 'P' from bk_bench_n where r <= cnt;
  commit;
  -- the deposits: one each on 30/12; one account in 10 a second one, its value date 31/12
  insert /*+ append */ into bk_entry (id, kind, book_date, value_date, descr, channel)
  select e0 + r, 'DEP', d1, d1, 'Bench', 'BR' from bk_bench_n where r <= cnt;
  commit;
  insert /*+ append */ into bk_entry (id, kind, book_date, value_date, descr, channel)
  select e0 + cnt + r, 'DEP', d1, d1 + 1, 'Bench, value 31/12', 'BR' from bk_bench_n where r <= ceil(cnt / 10);
  commit;
  insert /*+ append */ into bk_line (entry_id, account_id, gl_code, debit, credit, op, value_date)
  select e0 + r, null, 'CASH', 100 + mod(r * 7919, 49900), 0, null, d1 from bk_bench_n where r <= cnt
  union all
  select e0 + r, a0 + r, null, 0, 100 + mod(r * 7919, 49900), 'DEP', d1 from bk_bench_n where r <= cnt
  union all
  select e0 + cnt + r, null, 'CASH', 500, 0, null, d1 + 1 from bk_bench_n where r <= ceil(cnt / 10)
  union all
  select e0 + cnt + r, a0 + (r - 1) * 10 + 1, null, 0, 500, 'DEP', d1 + 1 from bk_bench_n where r <= ceil(cnt / 10);
  commit;
  merge into bk_account a
  using (select account_id, sum(credit - debit) b from bk_line where account_id > a0 group by account_id) x
  on (a.id = x.account_id)
  when matched then update set a.balance = x.b;
  commit;
  identity_on('bk_customer');
  identity_on('bk_account');
  identity_on('bk_entry');
  dbms_stats.gather_schema_stats(user);
  say(cnt || ' accounts with their deposits: ' || round((dbms_utility.get_time - t) / 100, 1) || ' s');

  t := dbms_utility.get_time;
  bk_core.close_day(d1);
  commit;
  say('close of 30/12 (a day as any other): ' || round((dbms_utility.get_time - t) / 100, 1) || ' s');
  t := dbms_utility.get_time;
  bk_core.close_day(d1 + 1);
  commit;
  say('close of 31/12 (all the accounts capitalize): ' || round((dbms_utility.get_time - t) / 100, 1) || ' s');
  select count(*) into k from bk_capital;
  say(k || ' capitalizations');
  select count(*) into k from bk_check;
  say('BK_CHECK: ' || k || ' rows');
end;
/
drop table if exists bk_bench_n purge;
exit
