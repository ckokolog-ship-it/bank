-- the credit cards (step 7). A credit card is an account of a product of kind CC (BK_ACCOUNT: its BALANCE below 0
-- is what is owed; double entry, BK_CHECK, the statement and the reports as any account) with a card of it
-- (BK_CARD: PAN, PIN, the ATM) and its terms:
--   BK_CC_PRODUCT  of the product: RATE % a year on what is owed, the MIN_PCT % of the balance of a statement to
--                  pay at least (and MIN_AMOUNT), by DUE_DAYS after it, the LATE_FEE when not
--   BK_CCARD       of the account: its CREDIT_LIMIT, HELD the authorizations not posted yet, STMT_DAY of its month
--                  (1 .. 28) its statement, LAST_STMT the day of the last one
--   BK_CC_AUTH     an authorization of a purchase: H held (its amount in HELD), P posted (its entry), R released
--   BK_CC_STATEMENT a statement: what was owed, purchases, payments, interest, fees, what is owed, the minimum
--                  and the day it is due; LATE_FEE when it was not paid by then
-- What may be spent: CREDIT_LIMIT + BALANCE - HELD, read and changed with the row of the account locked (every
-- authorization, purchase, payment, change of the limit), so two at once never pass the limit together
create table if not exists bk_cc_product (
  product_id  number        constraint bk_cc_product_pk primary key constraint bk_cc_product_fk references bk_product,
  rate        number(7,4)   not null constraint bk_cc_product_rate_ck check (rate >= 0),
  min_pct     number(5,2)   default 3 not null constraint bk_cc_product_pct_ck check (min_pct between 0 and 100),
  min_amount  number(18,2)  default 20 not null constraint bk_cc_product_min_ck check (min_amount >= 0),
  due_days    number(2)     default 25 not null constraint bk_cc_product_due_ck check (due_days between 1 and 27),
  late_fee    number(18,2)  default 0 not null constraint bk_cc_product_fee_ck check (late_fee >= 0)
);

