  select count(*) into n from user_tab_cols where table_name = 'BK_LINE' and column_name = 'OP';
  if n = 0 then
    execute immediate q'[alter table bk_line add (op varchar2(3)
                         constraint bk_line_op_ck check (op in ('DEP', 'WDR', 'TRO', 'TRI', 'OUT', 'INC', 'FEE')))]';
