create index if not exists bk_line_op_ix on bk_line (account_id, op);

-- the rules of the movements: for the whole bank (no product, no account), for a product, or for one account;
-- for a channel or for all of them (CHANNEL *). Each value from the most particular rule that has it (an
-- account before its product before the bank, a channel before all of them); none: no limit. A movement:
-- ALLOWED (N: not), its amount between MIN_AMOUNT and MAX_AMOUNT, the movements of the day and of the month up
-- to DAY_AMOUNT / DAY_COUNT and MONTH_AMOUNT / MONTH_COUNT (a limit of a channel: of that channel; of all of
-- them: all of them), FREE_MONTH of them free in a month and a FEE after them (FEE with no FREE_MONTH: every
-- time), MIN_BALANCE left in the account (money out)
create table if not exists bk_rule (
  id           number generated by default on null as identity constraint bk_rule_pk primary key,
  product_id   number        constraint bk_rule_product_fk references bk_product on delete cascade,
  account_id   number        constraint bk_rule_account_fk references bk_account on delete cascade,
  op           varchar2(3)   not null constraint bk_rule_op_ck check (op in ('DEP', 'WDR', 'TRO', 'TRI', 'OUT', 'INC')),
  channel      varchar2(3)   default '*' not null constraint bk_rule_channel_ck check (channel in ('*', 'BR', 'WEB', 'ATM')),
  allowed      varchar2(1)   constraint bk_rule_allowed_ck check (allowed in ('Y', 'N')),
  min_amount   number(18,2)  constraint bk_rule_min_ck check (min_amount >= 0),
  max_amount   number(18,2)  constraint bk_rule_max_ck check (max_amount >= 0),
  day_amount   number(18,2)  constraint bk_rule_damt_ck check (day_amount >= 0),
  day_count    number(5)     constraint bk_rule_dcnt_ck check (day_count >= 0),
  month_amount number(18,2)  constraint bk_rule_mamt_ck check (month_amount >= 0),
  month_count  number(5)     constraint bk_rule_mcnt_ck check (month_count >= 0),
  free_month   number(5)     constraint bk_rule_free_ck check (free_month >= 0),
  fee          number(18,2)  constraint bk_rule_fee_ck check (fee >= 0),
  min_balance  number(18,2),
  constraint bk_rule_one_ck check (product_id is null or account_id is null),
  constraint bk_rule_range_ck check (min_amount is null or max_amount is null or min_amount <= max_amount),
  constraint bk_rule_uk unique (product_id, account_id, op, channel)
);
create index if not exists bk_rule_account_ix on bk_rule (account_id);

