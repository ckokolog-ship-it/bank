-- the loans (step 8). A loan is an account of a product of kind LN (its BALANCE below 0: what is owed, its
-- principal and what fell due of it and is not paid yet), paid from an account of the customer (PAY_ACCOUNT_ID):
--   BK_LN_INDEX    the rates of an index (EURIBOR3M) by day: of a variable rate, the index + the margin
--   BK_LN_PRODUCT  of the product: RATE_TYPE F fixed (RATE) or V variable (INDEX_CODE + RATE, the margin, again
--                  every RESET_MONTHS), LATE_ADD % on what is late, LATE_FEE once, GRACE_DAYS before it is late,
--                  PREPAY_PCT a fee of a prepayment, MAX_MONTHS
--   BK_LOAN        of the account: its principal, months, its day of the month, the rate now
--   BK_LN_SCHEDULE its installments (annuity: principal + interest, the interest of a month: the balance x rate /
--                  1200): D to come, O due (its interest booked, being collected), L late, P paid; what was paid
--                  of each, its late fee and its late interest (accrued each day; booked at the end of a month, and
--                  when it is collected)
create table if not exists bk_ln_index (
  code        varchar2(20)  not null,
  day         date          not null,
  rate        number(7,4)   not null,
  constraint bk_ln_index_pk primary key (code, day)
);

create table if not exists bk_ln_product (
  product_id  number        constraint bk_ln_product_pk primary key constraint bk_ln_product_fk references bk_product,
  rate_type   varchar2(1)   default 'F' not null constraint bk_ln_product_type_ck check (rate_type in ('F', 'V')),
  rate        number(7,4)   not null constraint bk_ln_product_rate_ck check (rate >= 0),
  index_code  varchar2(20),
