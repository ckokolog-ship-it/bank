-- BK_TABLES.sql -- the tables of the bank: customers, products and their rates, accounts and their holders,
-- the accounts of the bank itself (GL), the entries in double entry (every entry: its debits equal its
-- credits; never changed, never deleted: a mistake is reversed by another entry), the interest of every
-- day, the days closed. A second run is safe: what exists stays.
--
-- The money: number(18,2); the interest of a day: number(18,6) (rounded only when it is capitalized).
-- Two dates on each entry: BOOK_DATE (the business day it was booked) and VALUE_DATE (from when it counts
-- for the interest).

create table if not exists bk_setting (
  name        varchar2(40)  constraint bk_setting_pk primary key,
  value       varchar2(400)
);

-- the currencies (ISO 4217): their decimals; SPREAD_PCT the margin of the bank on a conversion, each side of the
-- mid rate. The base currency of the bank: the setting BASE_CURRENCY (EUR), every line in it too (BASE_DEBIT,
-- BASE_CREDIT), at the rate of its day
create table if not exists bk_currency (
  code        varchar2(3)   constraint bk_currency_pk primary key
                            constraint bk_currency_code_ck check (regexp_like(code, '^[A-Z]{3}$')),
  name        varchar2(60 char) not null,
  decimals    number(1)     default 2 not null constraint bk_currency_dec_ck check (decimals between 0 and 3),
  spread_pct  number(5,3)   default 0.5 not null constraint bk_currency_spread_ck check (spread_pct between 0 and 10),
  active      varchar2(1)   default 'Y' not null constraint bk_currency_active_ck check (active in ('Y', 'N'))
);
insert into bk_currency (code, name, decimals, spread_pct)
select 'EUR', 'Ευρώ', 2, 0 from dual where not exists (select 1 from bk_currency where code = 'EUR');
commit;

-- the rates of the currencies: MID, how many of it one of the base currency buys (as the ECB: 1 EUR = 1,08 USD),
-- from its day on (the latest day before or on a day is the rate of that day); none of the base currency (1).
-- A heap table: a block of the forms reads its rows by their ROWID (the first one of PR 17 was organized by its
-- index: its rows kept, the table made again)
declare
  t varchar2(10);
begin
  select max(iot_type) into t from user_tables where table_name = 'BK_FX_RATE';
  if t = 'IOT' then
    execute immediate 'create table bk_fx_keep as select currency, day, mid from bk_fx_rate';
    execute immediate 'drop table bk_fx_rate purge';
  end if;
end;
/
create table if not exists bk_fx_rate (
  currency    varchar2(3)   not null constraint bk_fx_rate_currency_fk references bk_currency,
  day         date          not null,
  mid         number(18,8)  not null constraint bk_fx_rate_mid_ck check (mid > 0),
  constraint bk_fx_rate_pk primary key (currency, day)
);
declare
  n number;
begin
  select count(*) into n from user_tables where table_name = 'BK_FX_KEEP';
  if n > 0 then
    execute immediate 'insert into bk_fx_rate (currency, day, mid) select currency, day, mid from bk_fx_keep';
    execute immediate 'drop table bk_fx_keep purge';
    commit;
  end if;
end;
/

-- the customers: a person (or a company) with its tax number (AFM, its check digit right)
