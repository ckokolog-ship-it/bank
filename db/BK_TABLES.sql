-- the entries: DEP deposit, WDR withdrawal, TRF transfer, OUT a transfer to another bank, INC one from
-- another bank (a salary), INT interest capitalized (with its tax; of a credit card: charged), REV a reversal of
-- another one (once), PUR a purchase with a credit card, FEE a fee alone (of a credit card: paid late)
create table if not exists bk_entry (
  id          number generated by default on null as identity constraint bk_entry_pk primary key,
  kind        varchar2(3)   not null constraint bk_entry_kind_ck check (kind in ('DEP', 'WDR', 'TRF', 'OUT', 'INC', 'INT', 'REV', 'PUR', 'FEE')),
  book_date   date          not null,
  value_date  date          not null,
  descr       varchar2(200 char),
  reversal_of number        constraint bk_entry_rev_fk references bk_entry
                            constraint bk_entry_rev_uk unique,
  created_at  date          default sysdate not null,
  created_by  varchar2(60)  default coalesce(sys_context('userenv', 'client_identifier'), user) not null
);
create index if not exists bk_entry_book_ix on bk_entry (book_date);

-- the lines of an entry: a debit or a credit, of an account of a customer or of the bank
create table if not exists bk_line (
  id          number generated by default on null as identity constraint bk_line_pk primary key,
  entry_id    number        not null constraint bk_line_entry_fk references bk_entry,
  account_id  number        constraint bk_line_account_fk references bk_account,
