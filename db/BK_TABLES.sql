create index if not exists bk_holder_customer_ix on bk_holder (customer_id);

-- the accounts of the bank itself (GL): A asset, L liability, I income, E expense
create table if not exists bk_gl (
  code        varchar2(10)  constraint bk_gl_pk primary key,
  name        varchar2(60 char) not null,
  kind        varchar2(1)   not null constraint bk_gl_kind_ck check (kind in ('A', 'L', 'I', 'E'))
