-- the channel of an entry (BR the counter of a branch, WEB e-banking, ATM, SYS the bank itself: interest) and
-- the movement of each line of a customer (DEP deposit, WDR withdrawal, TRO transfer to another account of the
-- bank, TRI one from it, OUT to another bank, INC from another bank, FEE a fee): what the rules count
declare
  n number;
begin
  select count(*) into n from user_tab_cols where table_name = 'BK_ENTRY' and column_name = 'CHANNEL';
  if n = 0 then
    execute immediate q'[alter table bk_entry add (channel varchar2(3) default 'BR' not null
