-- BK_TABLES.sql -- the tables of the bank: customers, products and their rates, accounts and their holders,
-- the accounts of the bank itself (GL), the entries in double entry (every entry: its debits equal its
-- credits; never changed, never deleted: a mistake is reversed by another entry), the interest of every
-- day, the days closed. A second run is safe: what exists stays.
--
-- The money: number(18,2); the interest of a day: number(18,6) (rounded only when it is capitalized).
-- Two dates on each entry: BOOK_DATE (the business day it was booked) and VALUE_DATE (from when it counts
-- for the interest).

create table if not exists bk_setting (
  name        varchar2(40)  constraint bk_setting_pk primary key,
  value       varchar2(400)
);

-- the customers: a person (or a company) with its tax number (AFM, its check digit right)
create table if not exists bk_customer (
  id          number generated by default on null as identity constraint bk_customer_pk primary key,
  code        varchar2(12)  not null constraint bk_customer_code_uk unique,
  name        varchar2(100 char) not null,
  afm         varchar2(9)   constraint bk_customer_afm_uk unique
                            constraint bk_customer_afm_ck check (regexp_like(afm, '^[0-9]{9}$')),
  id_card     varchar2(20),
  birth_date  date,
  phone       varchar2(20),
  email       varchar2(100),
  address     varchar2(200 char),
  active      varchar2(1)   default 'Y' not null constraint bk_customer_active_ck check (active in ('Y', 'N')),
  created_at  date          default sysdate not null
);

-- the products of deposits: CUR current (όψεως), SAV savings (ταμιευτήριο), TD term deposit (προθεσμιακή);
-- how the interest is counted (DAY_BASIS: ACT365, ACT360, 30360), when it is capitalized (CAP_EVERY: M a
-- month, Q a quarter, Y a year), the tax withheld on it (TAX_RATE %), the debit interest of an overdraft
-- (OD_RATE % a year)
create table if not exists bk_product (
  id          number generated by default on null as identity constraint bk_product_pk primary key,
  code        varchar2(10)  not null constraint bk_product_code_uk unique,
  name        varchar2(60 char) not null,
  kind        varchar2(3)   not null constraint bk_product_kind_ck check (kind in ('CUR', 'SAV', 'TD')),
  day_basis   varchar2(6)   default 'ACT365' not null
                            constraint bk_product_basis_ck check (day_basis in ('ACT365', 'ACT360', '30360')),
  cap_every   varchar2(1)   default 'M' not null constraint bk_product_cap_ck check (cap_every in ('M', 'Q', 'Y')),
  tax_rate    number(5,2)   default 15 not null constraint bk_product_tax_ck check (tax_rate between 0 and 100),
  od_rate     number(7,4)   default 0 not null constraint bk_product_od_ck check (od_rate >= 0),
  active      varchar2(1)   default 'Y' not null constraint bk_product_active_ck check (active in ('Y', 'N'))
);

-- the rates of a product (% a year): each from a day on (VALID_FROM: its history), by tier (MIN_BALANCE: the
-- whole balance at the rate of the highest tier it reaches)
create table if not exists bk_rate (
  product_id  number        not null constraint bk_rate_product_fk references bk_product,
  valid_from  date          not null,
  min_balance number(18,2)  default 0 not null constraint bk_rate_min_ck check (min_balance >= 0),
  rate        number(7,4)   not null constraint bk_rate_rate_ck check (rate >= 0),
  constraint bk_rate_pk primary key (product_id, valid_from, min_balance)
);

-- the accounts: IBAN (GR, its check digits right), product, status (O open, B blocked: nothing out, C
-- closed), the limit of an overdraft; BALANCE the sum of its lines (credits less debits), ACCRUED the interest
-- not capitalized yet (+ to the customer, - an overdraft), ACCRUED_TO the last day of it
create table if not exists bk_account (
  id          number generated by default on null as identity constraint bk_account_pk primary key,
  iban        varchar2(27)  not null constraint bk_account_iban_uk unique
                            constraint bk_account_iban_ck check (regexp_like(iban, '^GR[0-9]{25}$')),
  product_id  number        not null constraint bk_account_product_fk references bk_product,
  name        varchar2(60 char),
  opened_on   date          not null,
  closed_on   date,
  status      varchar2(1)   default 'O' not null constraint bk_account_status_ck check (status in ('O', 'B', 'C')),
  od_limit    number(18,2)  default 0 not null constraint bk_account_od_ck check (od_limit >= 0),
  balance     number(18,2)  default 0 not null,
  accrued     number(18,6)  default 0 not null,
  accrued_to  date,
  constraint bk_account_closed_ck check ((status = 'C' and closed_on is not null) or (status <> 'C' and closed_on is null))
);
create index if not exists bk_account_product_ix on bk_account (product_id);

-- the holders of an account: one P (the primary), any J (joint)
create table if not exists bk_holder (
  account_id  number        not null constraint bk_holder_account_fk references bk_account on delete cascade,
  customer_id number        not null constraint bk_holder_customer_fk references bk_customer,
  role        varchar2(1)   default 'J' not null constraint bk_holder_role_ck check (role in ('P', 'J')),
  constraint bk_holder_pk primary key (account_id, customer_id)
);
create unique index if not exists bk_holder_primary_uk on bk_holder (case role when 'P' then account_id end);
create index if not exists bk_holder_customer_ix on bk_holder (customer_id);

-- the accounts of the bank itself (GL): A asset, L liability, I income, E expense
create table if not exists bk_gl (
  code        varchar2(10)  constraint bk_gl_pk primary key,
  name        varchar2(60 char) not null,
  kind        varchar2(1)   not null constraint bk_gl_kind_ck check (kind in ('A', 'L', 'I', 'E'))
);

-- the entries: DEP deposit, WDR withdrawal, TRF transfer, OUT a transfer to another bank, INC one from
-- another bank (a salary), INT interest
-- capitalized (with its tax), REV a reversal of another one (once)
create table if not exists bk_entry (
  id          number generated by default on null as identity constraint bk_entry_pk primary key,
  kind        varchar2(3)   not null constraint bk_entry_kind_ck check (kind in ('DEP', 'WDR', 'TRF', 'OUT', 'INC', 'INT', 'REV')),
  book_date   date          not null,
  value_date  date          not null,
  descr       varchar2(200 char),
  reversal_of number        constraint bk_entry_rev_fk references bk_entry
                            constraint bk_entry_rev_uk unique,
  created_at  date          default sysdate not null,
  created_by  varchar2(60)  default coalesce(sys_context('userenv', 'client_identifier'), user) not null
);
create index if not exists bk_entry_book_ix on bk_entry (book_date);

-- the lines of an entry: a debit or a credit, of an account of a customer or of the bank
create table if not exists bk_line (
  id          number generated by default on null as identity constraint bk_line_pk primary key,
  entry_id    number        not null constraint bk_line_entry_fk references bk_entry,
  account_id  number        constraint bk_line_account_fk references bk_account,
  gl_code     varchar2(10)  constraint bk_line_gl_fk references bk_gl,
  debit       number(18,2)  default 0 not null constraint bk_line_debit_ck check (debit >= 0),
  credit      number(18,2)  default 0 not null constraint bk_line_credit_ck check (credit >= 0),
  constraint bk_line_one_ck check ((account_id is null and gl_code is not null) or (account_id is not null and gl_code is null)),
  constraint bk_line_amount_ck check ((debit > 0 and credit = 0) or (credit > 0 and debit = 0))
);
create index if not exists bk_line_entry_ix on bk_line (entry_id);
create index if not exists bk_line_account_ix on bk_line (account_id, entry_id);

-- the channel of an entry (BR the counter of a branch, WEB e-banking, ATM, SYS the bank itself: interest) and
-- the movement of each line of a customer (DEP deposit, WDR withdrawal, TRO transfer to another account of the
-- bank, TRI one from it, OUT to another bank, INC from another bank, FEE a fee): what the rules count
declare
  n number;
begin
  select count(*) into n from user_tab_cols where table_name = 'BK_ENTRY' and column_name = 'CHANNEL';
  if n = 0 then
    execute immediate q'[alter table bk_entry add (channel varchar2(3) default 'BR' not null
                         constraint bk_entry_channel_ck check (channel in ('BR', 'WEB', 'ATM', 'SYS')))]';
  end if;
  select count(*) into n from user_tab_cols where table_name = 'BK_LINE' and column_name = 'OP';
  if n = 0 then
    execute immediate q'[alter table bk_line add (op varchar2(3)
                         constraint bk_line_op_ck check (op in ('DEP', 'WDR', 'TRO', 'TRI', 'OUT', 'INC', 'FEE')))]';
  end if;
end;
/
create index if not exists bk_line_op_ix on bk_line (account_id, op);

-- the rules of the movements: for the whole bank (no product, no account), for a product, or for one account;
-- for a channel or for all of them (CHANNEL *). Each value from the most particular rule that has it (an
-- account before its product before the bank, a channel before all of them); none: no limit. A movement:
-- ALLOWED (N: not), its amount between MIN_AMOUNT and MAX_AMOUNT, the movements of the day and of the month up
-- to DAY_AMOUNT / DAY_COUNT and MONTH_AMOUNT / MONTH_COUNT (a limit of a channel: of that channel; of all of
-- them: all of them), FREE_MONTH of them free in a month and a FEE after them (FEE with no FREE_MONTH: every
-- time), MIN_BALANCE left in the account (money out)
create table if not exists bk_rule (
  id           number generated by default on null as identity constraint bk_rule_pk primary key,
  product_id   number        constraint bk_rule_product_fk references bk_product on delete cascade,
  account_id   number        constraint bk_rule_account_fk references bk_account on delete cascade,
  op           varchar2(3)   not null constraint bk_rule_op_ck check (op in ('DEP', 'WDR', 'TRO', 'TRI', 'OUT', 'INC')),
  channel      varchar2(3)   default '*' not null constraint bk_rule_channel_ck check (channel in ('*', 'BR', 'WEB', 'ATM')),
  allowed      varchar2(1)   constraint bk_rule_allowed_ck check (allowed in ('Y', 'N')),
  min_amount   number(18,2)  constraint bk_rule_min_ck check (min_amount >= 0),
  max_amount   number(18,2)  constraint bk_rule_max_ck check (max_amount >= 0),
  day_amount   number(18,2)  constraint bk_rule_damt_ck check (day_amount >= 0),
  day_count    number(5)     constraint bk_rule_dcnt_ck check (day_count >= 0),
  month_amount number(18,2)  constraint bk_rule_mamt_ck check (month_amount >= 0),
  month_count  number(5)     constraint bk_rule_mcnt_ck check (month_count >= 0),
  free_month   number(5)     constraint bk_rule_free_ck check (free_month >= 0),
  fee          number(18,2)  constraint bk_rule_fee_ck check (fee >= 0),
  min_balance  number(18,2),
  constraint bk_rule_one_ck check (product_id is null or account_id is null),
  constraint bk_rule_range_ck check (min_amount is null or max_amount is null or min_amount <= max_amount),
  constraint bk_rule_uk unique (product_id, account_id, op, channel)
);
create index if not exists bk_rule_account_ix on bk_rule (account_id);

-- the interest of every day of every account: its balance by value date at the end of the day, the rate
-- (OD_RATE when below 0), the days it counts (1; 30/360: 0 the 31st, 3 or 2 the end of February) and the
-- divisor of its year; INTEREST = BALANCE x RATE / 100 x DAYS / YEAR_DAYS
create table if not exists bk_accrual (
  account_id  number        not null constraint bk_accrual_account_fk references bk_account,
  day         date          not null,
  balance     number(18,2)  not null,
  rate        number(7,4)   not null,
  days        number(2)     not null,
  year_days   number(3)     not null,
  interest    number(18,6)  not null,
  constraint bk_accrual_pk primary key (account_id, day)
);

-- the interest capitalized: when, how much (GROSS: the accrued rounded; TAX withheld), by which entry
create table if not exists bk_capital (
  account_id  number        not null constraint bk_capital_account_fk references bk_account,
  day         date          not null,
  gross       number(18,2)  not null,
  tax         number(18,2)  not null,
  entry_id    number        constraint bk_capital_entry_fk references bk_entry,
  constraint bk_capital_pk primary key (account_id, day)
);

-- the days closed (bk_core.close_day): the business day is the one after the last of them
create table if not exists bk_day (
  day         date          constraint bk_day_pk primary key,
  closed_at   date          default sysdate not null
);

-- the statement of an account: its lines in their order, the balance after each (the running balance)
create or replace view bk_statement as
select l.account_id, e.id entry_id, l.id line_id, e.kind, e.book_date, e.value_date, e.descr, e.reversal_of,
       l.debit, l.credit,
       sum(l.credit - l.debit) over (partition by l.account_id order by e.book_date, e.id, l.id
                                     rows unbounded preceding) balance
from bk_line l join bk_entry e on e.id = l.entry_id
where l.account_id is not null;

-- the balance of an account by value date at the end of each day it changed
create or replace view bk_value_balance as
select l.account_id, e.value_date, sum(l.credit - l.debit) amount
from bk_line l join bk_entry e on e.id = l.entry_id
where l.account_id is not null
group by l.account_id, e.value_date;

-- the check of the whole database: a row here is something that does not add up. Empty: every entry
-- balanced (its debits its credits, two lines at least), every balance the sum of its lines, every accrued
-- the interest of its days less what was capitalized, every account one primary holder, every IBAN right,
-- the days closed one after the other
create or replace view bk_check as
select 'ENTRY' what, to_char(e.id) ref, 'debits ' || nvl(sum(l.debit), 0) || ', credits ' || nvl(sum(l.credit), 0)
       || ', lines ' || count(l.id) detail
from bk_entry e left join bk_line l on l.entry_id = e.id
group by e.id
having nvl(sum(l.debit), 0) <> nvl(sum(l.credit), 0) or count(l.id) < 2
union all
select 'BALANCE', a.iban, 'balance ' || a.balance || ', lines ' || nvl(s.total, 0)
from bk_account a left join (select account_id, sum(credit - debit) total from bk_line group by account_id) s
  on s.account_id = a.id
where a.balance <> nvl(s.total, 0)
union all
select 'ACCRUED', a.iban, 'accrued ' || a.accrued || ', days ' || nvl(x.total, 0) || ', capitalized ' || nvl(c.total, 0)
from bk_account a
left join (select account_id, sum(interest) total from bk_accrual group by account_id) x on x.account_id = a.id
left join (select account_id, sum(gross) total from bk_capital group by account_id) c on c.account_id = a.id
where a.accrued <> nvl(x.total, 0) - nvl(c.total, 0)
union all
select 'HOLDER', a.iban, 'primary holders ' || (select count(*) from bk_holder h where h.account_id = a.id and h.role = 'P')
from bk_account a
where (select count(*) from bk_holder h where h.account_id = a.id and h.role = 'P') <> 1
union all
select 'IBAN', a.iban, 'check digits wrong'
from bk_account a
where mod(to_number(substr(a.iban, 5) || '1627' || substr(a.iban, 3, 2)), 97) <> 1
union all
select 'DAY', to_char(d.day, 'YYYY-MM-DD'), 'the day before it not closed'
from bk_day d
where d.day > (select min(day) from bk_day) and not exists (select 1 from bk_day p where p.day = d.day - 1);
