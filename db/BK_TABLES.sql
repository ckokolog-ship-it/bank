-- the products: of deposits CUR current (όψεως), SAV savings (ταμιευτήριο), TD term deposit (προθεσμιακή); CC a
-- credit card (its terms in BK_CC_PRODUCT; no interest of deposits on it); LN a loan (its terms in BK_LN_PRODUCT);
-- how the interest is counted (DAY_BASIS: ACT365, ACT360, 30360), when it is capitalized (CAP_EVERY: M a
-- month, Q a quarter, Y a year), the tax withheld on it (TAX_RATE %), the debit interest of an overdraft
-- (OD_RATE % a year)
create table if not exists bk_product (
  id          number generated by default on null as identity constraint bk_product_pk primary key,
  code        varchar2(10)  not null constraint bk_product_code_uk unique,
  name        varchar2(60 char) not null,
  kind        varchar2(3)   not null constraint bk_product_kind_ck check (kind in ('CUR', 'SAV', 'TD', 'CC', 'LN')),
  day_basis   varchar2(6)   default 'ACT365' not null
                            constraint bk_product_basis_ck check (day_basis in ('ACT365', 'ACT360', '30360')),
  cap_every   varchar2(1)   default 'M' not null constraint bk_product_cap_ck check (cap_every in ('M', 'Q', 'Y')),
  tax_rate    number(5,2)   default 15 not null constraint bk_product_tax_ck check (tax_rate between 0 and 100),
  od_rate     number(7,4)   default 0 not null constraint bk_product_od_ck check (od_rate >= 0),
  active      varchar2(1)   default 'Y' not null constraint bk_product_active_ck check (active in ('Y', 'N'))
);

-- the rates of a product (% a year): each from a day on (VALID_FROM: its history), by tier (MIN_BALANCE: the
-- whole balance at the rate of the highest tier it reaches)
create table if not exists bk_rate (
  product_id  number        not null constraint bk_rate_product_fk references bk_product,
  valid_from  date          not null,
  min_balance number(18,2)  default 0 not null constraint bk_rate_min_ck check (min_balance >= 0),
  rate        number(7,4)   not null constraint bk_rate_rate_ck check (rate >= 0),
  constraint bk_rate_pk primary key (product_id, valid_from, min_balance)
);

-- the accounts: IBAN (GR, its check digits right), product, status (O open, B blocked: nothing out, C
-- closed), the limit of an overdraft; BALANCE the sum of its lines (credits less debits), ACCRUED the interest
-- not capitalized yet (+ to the customer, - an overdraft), ACCRUED_TO the last day of it
create table if not exists bk_account (
  id          number generated by default on null as identity constraint bk_account_pk primary key,
  iban        varchar2(27)  not null constraint bk_account_iban_uk unique
                            constraint bk_account_iban_ck check (regexp_like(iban, '^GR[0-9]{25}$')),
  product_id  number        not null constraint bk_account_product_fk references bk_product,
  name        varchar2(60 char),
  opened_on   date          not null,
  closed_on   date,
  status      varchar2(1)   default 'O' not null constraint bk_account_status_ck check (status in ('O', 'B', 'C')),
  od_limit    number(18,2)  default 0 not null constraint bk_account_od_ck check (od_limit >= 0),
  balance     number(18,2)  default 0 not null,
  accrued     number(18,6)  default 0 not null,
  accrued_to  date,
  constraint bk_account_closed_ck check ((status = 'C' and closed_on is not null) or (status <> 'C' and closed_on is null))
