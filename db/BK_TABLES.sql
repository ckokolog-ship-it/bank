-- the currencies on what was there before them (all of it in the base currency, EUR): the currency of an account
-- (CURRENCIES: those its product opens in, the first of them by default), of a line and the line in the base
-- currency, of a rate of a product; an entry in another currency (ORIG_*: a purchase abroad, a transfer between
-- two currencies: the amount and the currency it was in, at FX_RATE); an authorization of a card in another
-- currency (its fee of conversion: FX_FEE, at FX_FEE_PCT of its product)
declare
  function missing(t varchar2, c varchar2) return boolean is
    n number;
  begin
    select count(*) into n from user_tab_cols where table_name = t and column_name = c;
    return n = 0;
  end;
  procedure add_(t varchar2, c varchar2, ddl varchar2) is
  begin
    if missing(t, c) then
      execute immediate 'alter table ' || t || ' add (' || ddl || ')';
    end if;
  end;
begin
  add_('BK_ACCOUNT', 'CURRENCY', q'[currency varchar2(3) default 'EUR' not null constraint bk_account_currency_fk references bk_currency]');
  add_('BK_PRODUCT', 'CURRENCIES', q'[currencies varchar2(200) default 'EUR' not null]');
  add_('BK_LINE', 'CURRENCY', q'[currency varchar2(3) default 'EUR' not null constraint bk_line_currency_fk references bk_currency]');
  if missing('BK_LINE', 'BASE_DEBIT') then
    execute immediate 'alter table bk_line add (base_debit number(18,2), base_credit number(18,2))';
    execute immediate 'update bk_line set base_debit = debit, base_credit = credit';
    commit;
  end if;
  add_('BK_ENTRY', 'ORIG_AMOUNT', 'orig_amount number(18,3), orig_currency varchar2(3), fx_rate number(18,8)');
  add_('BK_CC_AUTH', 'ORIG_AMOUNT', 'orig_amount number(18,3), orig_currency varchar2(3), fx_fee number(18,2) default 0 not null');
  add_('BK_CC_PRODUCT', 'FX_FEE_PCT', 'fx_fee_pct number(5,2) default 1.5 not null');
  if missing('BK_RATE', 'CURRENCY') then
    execute immediate q'[alter table bk_rate add (currency varchar2(3) default 'EUR' not null)]';
    execute immediate 'alter table bk_rate drop constraint bk_rate_pk';
    execute immediate 'alter table bk_rate add constraint bk_rate_pk primary key (product_id, currency, valid_from, min_balance)';
  end if;
end;
/

-- the statement of an account: its lines in their order, the balance after each (the running balance)
create or replace view bk_statement as
select l.account_id, e.id entry_id, l.id line_id, e.kind, e.book_date, e.value_date, e.descr, e.reversal_of,
       l.debit, l.credit,
       sum(l.credit - l.debit) over (partition by l.account_id order by e.book_date, e.id, l.id
                                     rows unbounded preceding) balance
from bk_line l join bk_entry e on e.id = l.entry_id
where l.account_id is not null;

-- the balance of an account by value date at the end of each day it changed
create or replace view bk_value_balance as
select l.account_id, e.value_date, sum(l.credit - l.debit) amount
from bk_line l join bk_entry e on e.id = l.entry_id
where l.account_id is not null
group by l.account_id, e.value_date;

-- the check of the whole database: a row here is something that does not add up. Empty: every entry
-- balanced in each currency (its debits its credits, two lines at least; every line in the base currency too, in
-- the currency of its account), every balance the sum of its lines, every accrued
-- the interest of its days less what was capitalized, every account one primary holder, every IBAN right,
-- the days closed one after the other
create or replace view bk_check as
select 'ENTRY' what, to_char(e.id) || case when l.currency is not null then ' ' || l.currency end ref,
       'debits ' || nvl(sum(l.debit), 0) || ', credits ' || nvl(sum(l.credit), 0) || ', lines ' || count(l.id) detail
from bk_entry e left join bk_line l on l.entry_id = e.id
group by e.id, l.currency
having nvl(sum(l.debit), 0) <> nvl(sum(l.credit), 0) or count(l.id) < 2
union all
select 'CURRENCY', to_char(l.id), 'line in ' || l.currency || ', its account in ' || a.currency
from bk_line l join bk_account a on a.id = l.account_id
where l.currency <> a.currency
union all
select 'BASE', to_char(l.id), 'no amount in the base currency'
from bk_line l
where l.base_debit is null or l.base_credit is null
union all
select 'BALANCE', a.iban, 'balance ' || a.balance || ', lines ' || nvl(s.total, 0)
from bk_account a left join (select account_id, sum(credit - debit) total from bk_line group by account_id) s
  on s.account_id = a.id
where a.balance <> nvl(s.total, 0)
union all
select 'ACCRUED', a.iban, 'accrued ' || a.accrued || ', days ' || nvl(x.total, 0) || ', capitalized ' || nvl(c.total, 0)
from bk_account a
left join (select account_id, sum(interest) total from bk_accrual group by account_id) x on x.account_id = a.id
left join (select account_id, sum(gross) total from bk_capital group by account_id) c on c.account_id = a.id
where a.accrued <> nvl(x.total, 0) - nvl(c.total, 0)
union all
select 'LINE', to_char(l.id), 'value date ' || to_char(l.value_date, 'YYYY-MM-DD') || ', of its entry '
       || to_char(e.value_date, 'YYYY-MM-DD')
from bk_line l join bk_entry e on e.id = l.entry_id
where l.value_date is null or l.value_date <> e.value_date
union all
select 'HOLDER', a.iban, 'primary holders ' || (select count(*) from bk_holder h where h.account_id = a.id and h.role = 'P')
from bk_account a
where (select count(*) from bk_holder h where h.account_id = a.id and h.role = 'P') <> 1
union all
select 'IBAN', a.iban, 'check digits wrong'
from bk_account a
where mod(to_number(substr(a.iban, 5) || '1627' || substr(a.iban, 3, 2)), 97) <> 1
union all
select 'DAY', to_char(d.day, 'YYYY-MM-DD'), 'the day before it not closed'
from bk_day d
where d.day > (select min(day) from bk_day) and not exists (select 1 from bk_day p where p.day = d.day - 1)
union all
select 'ATM', m.code, 'cash ' || m.cash || ', its cassettes ' || nvl(sum(n.note * n.pieces), 0)
from bk_atm m left join bk_atm_note n on n.atm_id = m.id
group by m.code, m.cash
having m.cash <> nvl(sum(n.note * n.pieces), 0)
union all
select 'CCHELD', a.iban, 'held ' || k.held || ', its authorizations ' || nvl(sum(h.amount), 0)
from bk_ccard k join bk_account a on a.id = k.account_id left join bk_cc_auth h on h.account_id = k.account_id and h.status = 'H'
group by a.iban, k.held
having k.held <> nvl(sum(h.amount), 0)
union all
select 'LOAN', a.iban, 'owed ' || -a.balance || ', principal ' || nvl(p.b_left, l.principal) || ', due and not paid '
       || nvl(o.due, 0)
from bk_loan l join bk_account a on a.id = l.account_id
left join (select account_id, max(balance) keep (dense_rank last order by n) b_left from bk_ln_schedule
           where status <> 'D' group by account_id) p on p.account_id = l.account_id
left join (select account_id, sum(payment + late_fee + late_booked - paid) due from bk_ln_schedule
           where status in ('O', 'L') group by account_id) o on o.account_id = l.account_id
where l.status = 'A' and -a.balance <> nvl(p.b_left, l.principal) + nvl(o.due, 0);

-- the kinds of products and of entries of the credit cards, in a database of before them
declare
  c varchar2(4000);
begin
